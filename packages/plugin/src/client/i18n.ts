export type DictKey = keyof (typeof DICTS)['en']
export type Locale = keyof typeof DICTS

export type Translate = (key: DictKey, params?: Record<string, string | number>) => string

export function formatDict(locale: Locale, key: DictKey, params?: Record<string, string | number>): string {
  let text: string = DICTS[locale][key] ?? DICTS.en[key]
  if (params !== undefined) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(`{${name}}`, String(value))
    }
  }
  return text
}
